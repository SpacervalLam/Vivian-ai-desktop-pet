import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import { readFileSync } from 'node:fs';
const bundle = buildSync({ entryPoints: ['src/components/mind-inspector/pages/notebookPageSource.ts'], bundle: true, write: false, format: 'cjs', platform: 'node' });
const mod = { exports: {} };
new Function('module', 'exports', bundle.outputFiles[0].text)(mod, mod.exports);
const { compilePageSource, sourceFromBlocks, pageEnter, pageInline, PageSourceError } = mod.exports;
const source = ':::section title="旅途"\n:::row columns=2 gap=20\n:::card title="左栏" color="#843d62" padding=16\n## 计划\n**出发**\n:::\n:::column\n:::callout\n带上雨伞\n:::\n:::\n:::\n:::';
const blocks = compilePageSource(source);
assert.equal(sourceFromBlocks(blocks), source, 'the authoring source survives exactly');
assert.match(blocks[0].html, /<section><h2/);
assert.match(blocks[0].html, /grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.match(blocks[0].html, /color:#843d62;padding:16px/);
assert.match(blocks[0].html, /<strong>出发<\/strong>/);
assert.match(blocks[0].html, /<aside class="callout"/);
assert.ok(blocks[0].html.indexOf('左栏') < blocks[0].html.indexOf('雨伞'));

const chart = { type: 'chart', chart_type: 'bar', categories: ['A'], series: [{ name: 'values', data: [42] }] };
const meta = { type: 'meta', key: 'provenance', text: 'invisible origin' };
const styled = { type: 'paragraph', text: 'old text', style: { bold: true, color: '#f00', font_size: 18 } };
const oldHtml = '<div class="custom-layout" style="display:grid"><strong>Original</strong></div>';
const original = [{ type: 'card', title: 'My card', body: 'Editable body' }, styled, { type: 'custom', html: oldHtml }, chart, { type: 'mermaid', code: 'graph TD\n A-->B', caption: 'Process' }, meta];
const importedSource = sourceFromBlocks(original);
assert.doesNotMatch(importedSource, /invisible origin/);
assert.match(importedSource, /:::card title="My card"/);
const edited = compilePageSource(importedSource.replace('Editable body', 'Updated body'));
assert.ok(edited.some(block => JSON.stringify(block) === JSON.stringify(styled)), 'original styled blocks survive prose edits');
assert.ok(edited.some(block => JSON.stringify(block) === JSON.stringify(chart)), 'charts stay native blocks for backend rendering');
assert.ok(edited.some(block => block.type === 'mermaid' && block.caption === 'Process'));
assert.ok(edited.some(block => block.type === 'custom' && block.html.includes(oldHtml)));
assert.equal(sourceFromBlocks(edited), importedSource.replace('Editable body', 'Updated body'));
const chartFirst = compilePageSource(`:::chart\n${JSON.stringify(chart)}\n:::\nAfter`);
assert.equal(chartFirst[0].html, '', 'source carrier does not duplicate a chart');
assert.deepEqual(chartFirst[1], chart);
assert.match(chartFirst[2].html, /After/);

assert.match(compilePageSource('| A | B |\n| --- | --- |\n| **yes** | no |')[0].html, /<table class="nb-table">/);
assert.match(compilePageSource('- parent\n  - child\n- [x] done')[0].html, /<li>parent<ul class="list"><li>child<\/li><\/ul><\/li><li><input/);
assert.match(compilePageSource(':::code\n:::not-a-wrapper\n<script>example</script>\n:::')[0].html, /&lt;script&gt;example/);
assert.match(compilePageSource('```html\n:::card\n<script>literal</script>\n```')[0].html, /&lt;script&gt;literal/);
assert.match(pageInline('<script>alert(1)</script>'), /&lt;script&gt;/);
assert.match(pageInline('![figure](C:/My Figures/figure(2).png)'), /src="C:\/My Figures\/figure\(2\).png"/);
const literalLegacy = compilePageSource(sourceFromBlocks([{ type: 'paragraph', text: ':::card\n**literal**\n## not a heading\n- not a list' }]));
assert.match(literalLegacy[0].html, /:::card<br>\*\*literal\*\*<br>## not a heading<br>- not a list/);
assert.doesNotMatch(compilePageSource(sourceFromBlocks([{ type: 'paragraph', text: '| A | B |\n--- | ---\n| C | D |' }]))[0].html, /<table/);
assert.doesNotMatch(pageInline('[unsafe](javascript:alert(1))'), /href=/);
assert.doesNotMatch(pageInline('![unsafe](data:text/html;base64,AAAA)'), /<img/);
assert.match(compilePageSource(':::image src="https://example.com/a.jpg" caption="A"\n:::')[0].html, /<figcaption class="image-caption">A/);

for (const invalid of [':::card\nunfinished', ':::', ':::unknown\n:::', ':::text color="red;position:fixed"\ntext\n:::', ':::row columns=99\n:::', ':::chart\n{bad}\n:::', ':::chart\n{"chart_type":"bar","categories":[],"series":[{"data":[1]}]}\n:::', ':::card\n:::mermaid\ngraph TD\n A-->B\n:::\n:::']) {
  assert.throws(() => compilePageSource(invalid), PageSourceError, invalid);
}
const quotedTitle = sourceFromBlocks([{ type: 'card', title: 'A "quoted" title', body: 'Body' }]);
assert.match(compilePageSource(quotedTitle)[0].html, /A &quot;quoted&quot; title/);
const delimiterHtml = '<pre>\n:::\n</pre>';
const delimiterBlocks = compilePageSource(sourceFromBlocks([{ type: 'custom', html: delimiterHtml }]));
assert.ok(delimiterBlocks.some(b => b.type === 'custom' && b.html === delimiterHtml));
const legacy = '**Old source**\n\n- [ ] task';
assert.equal(sourceFromBlocks([{ type: 'custom', html: '<p>cache</p>', markdown: legacy }]), legacy);
assert.match(compilePageSource(legacy)[0].html, /<strong>Old source/);
for (const [value, expected] of [['- item', '\n- '], ['12. item', '\n13. '], ['  - [x] done', '\n  - [ ] '], ['> quote', '\n> '], ['plain', '\n'], [':::html\n- literal', '\n'], ['```\n- literal', '\n']]) assert.equal(pageEnter(value, value.length, value.length).text, expected);
assert.deepEqual(pageEnter('hello\n- ', 8, 8), { start: 6, end: 8, text: '\n' });
assert.deepEqual(pageEnter(':::card', 7, 7), { start: 7, end: 7, text: '\n\n:::', caret: 8 }, 'Enter closes a new wrapper and places the cursor inside it');
assert.equal(pageEnter(':::html\n:::card', 15, 15).text, '\n', 'native HTML does not inherit wrapper auto-closing');
const page = readFileSync('src/components/mind-inspector/pages/NotebookPage.tsx', 'utf8');
assert.doesNotMatch(page, /WysiwygEditor|BlockEditor|setMode|mode_form|mode_wysiwyg|NotebookMarkdown/);
assert.match(page, /NotebookPageEditor/);
assert.doesNotMatch(readFileSync('src/components/mind-inspector/pages/NotebookPageEditor.tsx', 'utf8'), /Markdown|docHtml/);
console.log('Page source: nested HTML wrappers, styles, native charts, legacy source, source preservation, errors and keyboard behavior passed.');
