import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
const bundle = buildSync({ entryPoints: ['src/components/mind-inspector/pages/sessionSidebarModel.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { readSessionGroups, recentSidebarSessions, sidebarProjects, removeSessionGroup } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const sessions = Array.from({ length: 80 }, (_, index) => ({ session_id: `session-${index}`, title: `完整标题 ${index}`, working_directory: index % 3 ? '' : 'G:\\vivian-rs', updated_at: index, status: 'idle', channel: ['desktop', 'companion', 'remote'][index % 3] }));
const recent = recentSidebarSessions(sessions);
assert.equal(recent.length, 40);
assert.equal(recent[0].session_id, 'session-79');
assert.equal(recent.at(-1).session_id, 'session-40');
assert.equal(new Set(recent.map(session => session.channel)).size, 3);
assert.equal(recentSidebarSessions([...sessions, sessions[79]]).length, 40);
const projects = sidebarProjects([...sessions, { ...sessions[0], session_id: 'same-path', working_directory: 'g:/VIVIAN-RS/' }]);
assert.equal(projects.length, 1);
assert.equal(projects[0].sessions.length, 28);
assert.ok(projects[0].sessions.some(session => session.session_id === 'session-0'), 'old workspaces must survive the recent-40 limit');
assert.equal(sidebarProjects([{ ...sessions[0], working_directory: ' /tmp/A ' }, { ...sessions[1], working_directory: '/tmp/a' }]).length, 2, 'Unix paths remain case-sensitive');
const state = readSessionGroups(JSON.stringify({ groups: [{ id: 'projects', name: 'hijacked' }, { id: 'recent', name: 'hijacked' }, { id: 'study', name: ' 学习 ' }, { id: 'study', name: 'duplicate' }], membership: { 'session-79': 'study', 'session-40': 'missing' } }));
assert.deepEqual(state.groups, [{ id: 'study', name: '学习' }]);
assert.deepEqual(state.membership, { 'session-79': 'study' });
assert.deepEqual(readSessionGroups(JSON.stringify(state)), state, 'groups and membership persist across reopening');
assert.equal(removeSessionGroup(state, 'projects'), state);
assert.equal(removeSessionGroup(state, 'recent'), state);
assert.deepEqual(removeSessionGroup(state, 'study'), { groups: [], membership: {} });
assert.equal(sessions.length, 80, 'deleting a group never deletes session data');
assert.deepEqual(readSessionGroups('{broken'), { groups: [], membership: {} });
console.log('Session sidebar: global latest 40 across channels, all workspace projects, path normalization, immutable special groups and persisted custom membership passed.');
