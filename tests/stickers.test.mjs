import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=async(entry)=>{const r=await build({stdin:{contents:`
 import {registerCharacters} from './src/characters';
 export * from './${entry}';
 export { registerCharacters };
`,resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm',plugins:[{name:'mock-tauri',setup(b){b.onResolve({filter:/^@tauri-apps\/api\/core$/},()=>({path:'tauri',namespace:'mock'}));b.onLoad({filter:/.*/,namespace:'mock'},()=>({contents:'export function invoke(command,args){globalThis.__stickerCalls.push(args.sticker);return Promise.resolve("data:image/png;base64,dummy")}'}));}}]});return import('data:text/javascript;base64,'+Buffer.from(r.outputFiles[0].text).toString('base64'));};
const {parseSticker,stickerSource,stickerCategory,stickerLabel,registerCharacters}=await bundle('src/components/stickers/stickers.ts');
const {isVisibleChatMessage}=await bundle('src/utils/chatMessageContent.ts');
const sticker={id:'vivian_happy_01',character_id:'vivian',version:'1',label:'开心',meaning:'轻松的喜悦'};
assert.deepEqual(parseSticker(sticker),sticker);
assert.equal(parseSticker({...sticker,id:'../outside'}),undefined);
assert.equal(parseSticker({...sticker,character_id:'nana'}),undefined);
assert.equal(parseSticker({...sticker,version:'../../outside'}),undefined);
const packagedStickers = ['deepseek','claude'].map(character_id => ({...sticker,id:`${character_id}_custom_1`,character_id}));
for (const packaged of packagedStickers) assert.equal(parseSticker(packaged),undefined);
registerCharacters(packagedStickers.map(({character_id}) => ({ id: character_id, name: character_id })));
for (const packaged of packagedStickers) assert.deepEqual(parseSticker(packaged),packaged);
assert.equal(stickerCategory(sticker),'happy');
assert.equal(stickerCategory({...sticker,id:'vivian_ds_peek_01'}),'peek');
assert.equal(stickerCategory({...sticker,id:'vivian_custom_1',category:'comfort'}),'comfort');
assert.equal(parseSticker({...sticker,category:{}}),undefined);
assert.equal(parseSticker({...sticker,category:'../happy'}),undefined);
assert.equal(stickerLabel({...sticker,version:'2',label:'薇薇安 · 开心'}).includes('薇薇安'),false);
assert.equal(isVisibleChatMessage({role:'assistant',content:'',sticker}),true);
assert.equal(isVisibleChatMessage({role:'assistant',content:''}),false);
globalThis.__stickerCalls=[];
await Promise.all([stickerSource(sticker),stickerSource({...sticker})]);assert.equal(globalThis.__stickerCalls.length,1);
await stickerSource({...sticker,version:'newversion'});assert.equal(globalThis.__stickerCalls.length,2);
console.log('Sticker checks passed: standalone visibility, scoped IDs, path validation and versioned resource cache.');
