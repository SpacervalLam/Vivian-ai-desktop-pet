import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
const { outputFiles } = buildSync({ entryPoints: ['src/components/mind-inspector/pages/browserOverlayFrame.ts'], bundle: true, write: false, format: 'esm', platform: 'node' });
const { BrowserOverlayCapture, unobscuredBrowserRect } = await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`);
const png = 'data:image/png;base64,iVBORw0KGgo=';
const tick = () => new Promise(resolve => setImmediate(resolve));
const commits = [];
const capture = new BrowserOverlayCapture(frame => commits.push(frame));
let resolveFirst, calls = 0;
const delayed = () => { calls++; return new Promise(resolve => { resolveFirst = resolve; }); };
capture.request('tab-a', delayed); capture.request('tab-a', delayed);
await tick(); assert.equal(calls, 1, 'RAF polling must not duplicate pending captures');
assert.equal(capture.ready('tab-a'), false, 'native surface stays visible while capture is pending');
resolveFirst(png); await tick();
assert.equal(capture.ready('tab-a'), false, 'native surface stays visible until replacement is decoded and mounted');
assert.equal(commits.at(-1).image, png);
capture.markReady('tab-a', { key: 'tab-a', image: png });
assert.equal(capture.ready('tab-a'), false, 'an old image load cannot mark a replacement frame ready');
capture.markReady('tab-a'); assert.equal(capture.ready('tab-a'), true);
capture.request('tab-a', delayed); await tick(); assert.equal(calls, 1, 'one capture across menu/submenu changes');
capture.clear(); assert.equal(commits.at(-1), null); assert.equal(capture.active(), false);
capture.request('tab-a', delayed); await tick();
capture.clear(); resolveFirst(png); await tick();
assert.equal(commits.at(-1), null, 'closing before capture finishes discards the late image');
capture.request('old-tab', delayed); await tick();
const oldResult = resolveFirst;
capture.request('new-tab', async () => png); await tick();
oldResult(png); await tick();
assert.equal(commits.at(-1).key, 'new-tab', 'navigation cannot install a stale snapshot');
capture.markReady('old-tab'); assert.equal(capture.ready('new-tab'), false);
capture.markReady('new-tab'); capture.fail('new-tab');
assert.equal(capture.ready('new-tab'), false); assert.equal(capture.hasFailed('new-tab'), true);
capture.clear(); capture.request('bad', async () => 'javascript:wrong'); await tick();
assert.equal(capture.hasFailed('bad'), true); assert.equal(capture.ready('bad'), false);
capture.clear(); capture.request('rejected', async () => { throw Error('fixture failure'); }); await tick();
assert.equal(capture.hasFailed('rejected'), true);
const viewport = { x: 10, y: 100, width: 1000, height: 600 };
const menus = [{ x: 730, y: 90, width: 280, height: 500 }, { x: 400, y: 150, width: 320, height: 250 }];
const free = unobscuredBrowserRect(viewport, menus);
assert.ok(free.width * free.height > 0, 'capture failure preserves a live unobscured page area');
for (const menu of menus) assert.ok(free.x >= menu.x + menu.width || free.x + free.width <= menu.x || free.y >= menu.y + menu.height || free.y + free.height <= menu.y);
assert.deepEqual(unobscuredBrowserRect(viewport, []), viewport);
assert.equal(unobscuredBrowserRect(viewport, [viewport]).width, 0);
console.log('Browser overlays: capture deduplication, decode gate, close/navigation races, disposal, invalid images and live-page fallback passed.');
