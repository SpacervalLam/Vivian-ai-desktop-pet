/**
 * 北侧小河与电车跨河桥的几何单点真相。
 *
 * 这条河横跨整个世界的东西向（与 `buildExteriorGround` 的世界地面同宽），在它和
 * 南北两条电车轨道（x=86 / 91，见 sakuraStation）相交的那一段，路基换成铁路桥。
 * 涉及三个互相独立的模块，坐标必须在它们之间保持一致，否则会出现"桥不在河上"：
 *
 *   - `exterior.ts`      世界地面在此断开成南北两片，缺口里长河床 / 护岸 / 水面
 *   - `sakuraStation.ts` 轨道的道砟、枕木、栅栏在此断开，换成正跨在缺口上的桥
 *   - `districtArt.ts`   远景低模楼避开河道，不让它直接立在水里
 *
 * 所以常量集中在这里，跟 `trainSchedule.ts` 的 TRACK_HALF 是同一套做法：
 * 偏移量一旦改，三处同时跟着变，不存在某一处抄漏。
 */

/* ---------------- 平面位置 ----------------
 *
 * 中心线取 z = -95，南北各 7m（河宽 14m）。取值卡在两个已经落位的邻居之间：
 *
 *   - 北面第一排远景低模楼 `skyline-n` 落在 z = -112，footprint 深度 ±5.5m，
 *     南边缘到 -106.5 —— 离本河的北岸 4.5m，两不相犯。
 *   - 街区最北的可步行面是 `WALK_BOUNDS.z0 = -78`（districtArt），距南岸 10m。
 *     玩家走到最北也够不着水，于是省掉一整套"防止掉进河"的护栏碰撞与坠落判定。
 *
 * 东西两端刻意与世界地面同宽（±500，见 exterior 的 SIZE）。原因是同样的那一句：
 * 要在任何可站立点都看不到"河尽头"。玩家最远的观景点是 (150, 95)，看向西北端
 * 超过 500m，晴天雾 far=300 —— 河道与世界地面一样在雾里消失，不会比地面先断。
 * 河道本身是一张平面加两条护岸，加长的顶点代价为零。
 */
/** 河道南岸 / 北岸边缘的世界 z（负向为北）。 */
export const RIVER_Z_S = -88;
export const RIVER_Z_N = -102;
/** 中心线 z 与半宽。 */
export const RIVER_CZ = (RIVER_Z_S + RIVER_Z_N) / 2;
export const RIVER_HALF = (RIVER_Z_S - RIVER_Z_N) / 2;

/* ---------------- 标高 ----------------
 *
 * 河必须落在**低于**街面的标高上。世界地面是一张不透明的大平面，任何盖在它上面的
 * 水面都会被它挡住 —— 要看见水，只能让地面在河道处真的开个口子。
 *
 * 所以 -1.55 不是随手取的，它是"往下挖多少还能看清"这条权衡的解：
 *
 *   - 挖太浅，桥梁体塞不进去。轨面被 `PT_RAISE` 锁死在 0.51（见 sakuraStation），
 *     桥面板顶面只能与道砟底面齐平（0.12），面板厚 0.35、两侧主梁再往下 0.2，
 *     梁腹底到 -0.43。水面要在 -0.6 以下才有起码的梁下净空。
 *   - 挖太深，**水面就看不见了**，而且不是"变窄一点"而是"整条消失"——这一条是
 *     第一版（水面 -1.55）踩出来的，也是本次改浅的全部原因：
 *
 *     玩家站不到河边：`WALK_BOUNDS.z0 = -78`（districtArt）离南岸还有 10m。站在这
 *     个最近点上、眼高 1.7m，掠过南岸那道沿（地面边缘）的视线，还得再往前
 *     `w·D/h` 米才够得着水面（w = 水面低于地面的深度、D = 到岸边的水平距离、
 *     h = 眼高）。越过这个距离之后的水面才可见，之前的部分全被岸沿本身挡住。
 *
 *       w=1.55（第一版）：z=-78 处要 9.1m → 只剩 3.2m 可见；z=-69 那条东西向
 *         马路上要 17.3m → **整条水面被挡光**，站那儿只看得到两岸斜坡。
 *       w=0.85（现在）：  z=-78 处 5.0m → 7.7m 可见；z=-69 处 9.5m → 3.2m 可见。
 *         算账脚本 tmp/_river-sightline.mjs。
 *
 *     同一条几何还给出一条硬约束，riverbank 必须遵守：**岸边连续的构件每往外
 *     退 1m，才允许高 0.17m**（= h/D，取最苛刻的 z=-78 视点）。所以防汛墙不能贴
 *     着岸边立——那等于把这条河自己挡死。
 */
/** 常水面标高。 */
export const RIVER_SURFACE_Y = -0.85;
/** 河床标高。水深 1.05m，是被混凝土渠化过的那种城市小河。 */
export const RIVER_BED_Y = -1.9;
/** 护岸顶（= 街面）。河岸与街面齐平，只是中间塌下去 1.55m。 */
export const RIVER_BANK_Y = 0;

/* ---------------- 铁路桥 ----------------
 *
 * 跨度 21m，比河宽多出两岸各 3.5m 的搭头 —— 桥台要坐在实地上，不能悬在护岸墙头。
 */
/** 南 / 北桥台的世界 z。 */
export const BRIDGE_Z_S = -84.5;
export const BRIDGE_Z_N = -105.5;
/**
 * 桥宽包住两条走行轨各自的道床（x ∈ [84.1, 87.9] 与 [89.1, 92.9]，每条道床宽 3.8m，
 * 见 sakuraStation），两侧再各留 0.6m 检修道。道砟是铺到道床边缘的，桥面收得比
 * 道床窄就会看见轨道悬空。
 */
export const BRIDGE_X0 = 83.3;
export const BRIDGE_X1 = 93.7;
/**
 * 桥面板顶面。**与道砟底面同高（0.12）**：桥面之上直接铺枕木和钢轨，标高与区间
 * 路基完全一致，列车过桥时不会有哪怕一点起伏。
 */
export const BRIDGE_DECK_Y = 0.12;
/** 桥面板厚。 */
export const BRIDGE_DECK_THICK = 0.35;
/** 两侧主梁底面：面板底下再往下 0.2m。多留的每 1cm 都在吃梁下净空（见上方深度权衡）。 */
export const BRIDGE_GIRDER_Y = BRIDGE_DECK_Y - BRIDGE_DECK_THICK - 0.2;

/** 某段 z 是否落在桥跨内 —— 给需要"这一段不许铺道砟 / 不许架接触网柱"的模块用。 */
export const inBridgeSpan = (z: number) => z > BRIDGE_Z_N && z < BRIDGE_Z_S;

/**
 * 坐标系偏移。
 *
 * `buildExteriorGround` 产出的 Group 会被 RoomScene 平移到房间包围盒中心
 * （`position.set((B.x0+B.x1)/2, 0, (B.z0+B.z1)/2)`），而本模块和 sakuraStation
 * 用的都是真实世界坐标 —— 于是同一个 z 常量在两套坐标系里相差
 * `(B.z0 + B.z1) / 2 = 0.2m`。
 *
 * 这 0.2m 与地铁竖井身上已有的情况同源（exterior 的 `PIT_*` 同样自称 world coords，
 * 实际也躺在这个偏差上）。它对本次改动无害：桥台有 3.5m 搭头，0.2m 只占 5.7%，
 * 任何机位都读不出来。这里只记账、不去顺手改 —— 改它是另一笔账：要把 dormLayout
 * 的 bounds 引进 exterior，并同时校正已经验收过的 PIT 竖井。
 */
export const GROUND_SHIFT = 0.2;
